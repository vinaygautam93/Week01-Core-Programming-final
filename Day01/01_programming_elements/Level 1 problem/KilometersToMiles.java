
public class KilometersToMiles {
      public static void main( String []args ) {
	           //total distance in kilometers
	           double distanceInkilometer = 10.8;
                   //Calculating result
		   double result = distanceInkilometer * 1.6; // 1 km = 1.6 miles
		   
                   //Displaying result
		   System.out.println( " The distance " + 10.6 + "  km in miles is " + result );
		   
	    }
}		
		   
		   